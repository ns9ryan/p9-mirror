BEGIN;

CREATE TABLE public.timezone (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    name_key VARCHAR(128) NOT NULL,
    status SMALLINT NOT NULL DEFAULT 1 CHECK (status IN (1, 2)),
    sort_no INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE public.timezone IS '系统时区表';
COMMENT ON COLUMN public.timezone.id IS '主键ID';
COMMENT ON COLUMN public.timezone.code IS 'IANA时区编码';
COMMENT ON COLUMN public.timezone.name_key IS '名称翻译Key';
COMMENT ON COLUMN public.timezone.status IS '1启用，2停用';
COMMENT ON COLUMN public.timezone.sort_no IS '排序值，越小越靠前';
COMMENT ON COLUMN public.timezone.created_at IS '创建时间';
COMMENT ON COLUMN public.timezone.updated_at IS '更新时间';

